#!/usr/bin/env python3
"""Download the Cburnett chess pieces from Wikimedia Commons and convert them
to C arrays (RGB565 colour + 8-bit alpha) for lib/ChessCore/src/gen/pieces.h.

Usage:  python scripts/gen_pieces.py   (needs Pillow: pip install pillow)

Why PNG renders instead of the SVGs: Commons renders every SVG to PNG on its
own servers (librsvg), so we don't need an SVG rasteriser installed locally.
We fetch a large render and downsample it ourselves with Pillow.
"""
import io
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "build" / "cache" / "pieces"
OUT = ROOT / "lib" / "ChessCore" / "src" / "gen" / "pieces.h"

SIZE = 60          # one board square is 60x60 px; the SVG already has margins
FETCH_WIDTH = 500  # a standard Commons thumbnail width
UA = "chessMagnet-asset-script/1.0 (personal hobby project)"

# Order must match chess::Piece (WHITEPAWN=0 .. WHITEKING=5, BLACKPAWN=6 ..)
PIECES = [(c, p) for c in "ld" for p in "pnbrqk"]


def http_get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return r.read()
        except Exception as e:  # retry flaky connections
            if attempt == 3:
                raise
            print(f"  retry ({e})")
            time.sleep(2 * (attempt + 1))
    raise RuntimeError("unreachable")


def file_info(title: str) -> dict:
    q = urllib.parse.urlencode({
        "action": "query", "titles": title, "format": "json",
        "prop": "imageinfo|revisions", "iiprop": "url|extmetadata",
        "iiurlwidth": FETCH_WIDTH, "rvprop": "content", "rvslots": "main",
    })
    data = json.loads(http_get("https://commons.wikimedia.org/w/api.php?" + q))
    page = next(iter(data["query"]["pages"].values()))
    info = page["imageinfo"][0]
    wikitext = page["revisions"][0]["slots"]["main"]["*"]
    return {"thumb": info["thumburl"], "page": info["descriptionurl"],
            "artist": info["extmetadata"]["Artist"]["value"],
            "wikitext": wikitext}


def to565(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main() -> int:
    CACHE.mkdir(parents=True, exist_ok=True)
    rgb_arrays, alpha_arrays, credits = [], [], []
    for colour, piece in PIECES:
        name = f"Chess_{piece}{colour}t45.svg"
        png_path = CACHE / (name + f".{FETCH_WIDTH}.png")
        info = file_info("File:" + name)
        # Licence check: every Cburnett piece carries this multi-licence tag.
        if "{{self|GFDL|migration=relicense|BSD|GPL}}" not in info["wikitext"].replace(" ", ""):
            print(f"!! unexpected licence on {name}; check {info['page']}")
            return 1
        if "Cburnett" not in info["artist"]:
            print(f"!! unexpected author on {name}")
            return 1
        if not png_path.exists():
            print(f"downloading {name}")
            png_path.write_bytes(http_get(info["thumb"]))
            time.sleep(1.5)  # be polite: Commons rate-limits rapid downloads
        credits.append(info["page"])

        img = Image.open(io.BytesIO(png_path.read_bytes())).convert("RGBA")
        # Resize in premultiplied-alpha mode ("RGBa") so transparent pixels'
        # (meaningless) colour does not bleed into the antialiased edges.
        img = img.convert("RGBa").resize((SIZE, SIZE), Image.LANCZOS).convert("RGBA")
        px = [img.getpixel((x, y)) for y in range(SIZE) for x in range(SIZE)]
        rgb_arrays.append([to565(r, g, b) if a else 0 for r, g, b, a in px])
        alpha_arrays.append([a for _, _, _, a in px])

    def fmt(vals, width, per_line):
        lines = []
        for i in range(0, len(vals), per_line):
            lines.append("    " + ",".join(f"0x{v:0{width}X}" for v in vals[i:i + per_line]) + ",")
        return "\n".join(lines)

    names = [f"{'white' if c == 'l' else 'black'} {p}" for c, p in PIECES]
    out = [
        "// GENERATED by scripts/gen_pieces.py -- do not edit by hand.",
        "//",
        "// Chess pieces by Cburnett (https://commons.wikimedia.org/wiki/User:Cburnett),",
        "// from Wikimedia Commons. Multi-licensed by the author under GFDL, BSD and GPL;",
        "// used here under the 3-clause BSD licence. See README.md for the full credit.",
        "// Source pages:",
        *[f"//   {u}" for u in credits],
        "//",
        f"// Each piece is {SIZE}x{SIZE} px, row-major. Index = chess::Piece value.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace gen {",
        f"constexpr int kPieceSize = {SIZE};",
        f"static const uint16_t kPieceRGB565[12][{SIZE * SIZE}] = {{",
    ]
    for n, arr in zip(names, rgb_arrays):
        out += [f"  {{ // {n}", fmt(arr, 4, 16), "  },"]
    out += ["};", f"static const uint8_t kPieceAlpha[12][{SIZE * SIZE}] = {{"]
    for n, arr in zip(names, alpha_arrays):
        out += [f"  {{ // {n}", fmt(arr, 2, 24), "  },"]
    out += ["};", "}  // namespace gen", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB source)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
