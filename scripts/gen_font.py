#!/usr/bin/env python3
"""Rasterise Fira Sans Bold into small antialiased bitmap fonts (4-bit alpha)
for lib/ChessCore/src/gen/fonts.h.

Usage:  python scripts/gen_font.py   (needs Pillow)

Why our own font format: the same renderer runs on the ESP32 and on the PC
(for the preview), so it can't depend on Arduino_GFX's font code.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "assets" / "fonts" / "FiraSans-Bold.ttf"
OUT = ROOT / "lib" / "ChessCore" / "src" / "gen" / "fonts.h"
SIZES = {"Tiny": 14, "Small": 22, "Large": 40}  # Tiny = board coordinates
FIRST, LAST = 32, 126  # printable ASCII


def build(name: str, px: int) -> list[str]:
    font = ImageFont.truetype(str(TTF), px)
    ascent, descent = font.getmetrics()
    glyphs, nibbles = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")  # relative to baseline
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(nibbles)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            for y in range(h):
                for x in range(w):
                    nibbles.append((img.getpixel((x, y)) + 8) // 17)  # 0..255 -> 0..15
        glyphs.append((offset, w, h, x0, y0, advance, ch))
    if len(nibbles) % 2:
        nibbles.append(0)
    packed = [(nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)]

    out = [f"// {name}: Fira Sans Bold {px}px, ascent {ascent}, descent {descent}",
           f"static const uint8_t k{name}Bits[{len(packed)}] = {{"]
    for i in range(0, len(packed), 24):
        out.append("    " + ",".join(f"0x{b:02X}" for b in packed[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const Glyph k{name}Glyphs[{len(glyphs)}] = {{")
    for off, w, h, xo, yo, adv, ch in glyphs:
        label = {"\\": "backslash", "'": "quote"}.get(ch, ch)
        out.append(f"    {{{off}, {w}, {h}, {xo}, {yo}, {adv}}},  // {label}")
    out.append("};")
    out.append(f"static const Font k{name} = {{k{name}Bits, k{name}Glyphs, "
               f"{FIRST}, {LAST}, {ascent}, {descent}}};")
    out.append("")
    return out


def main() -> int:
    out = [
        "// GENERATED by scripts/gen_font.py -- do not edit by hand.",
        "// Fira Sans Bold, Copyright (c) 2012-2015 The Mozilla Foundation and",
        "// Telefonica S.A., SIL Open Font License 1.1 (assets/fonts/OFL.txt).",
        "// Glyph bitmaps are 4-bit alpha, two pixels per byte, high nibble first;",
        "// 'offset' counts pixels (nibbles), not bytes.",
        "#pragma once",
        "#include \"../font.h\"",
        "",
        "namespace gen {",
    ]
    for name, px in SIZES.items():
        out += build(name, px)
    out += ["}  // namespace gen", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
